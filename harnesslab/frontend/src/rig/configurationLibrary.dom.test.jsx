// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ConfigurationLibrary } from './configurationLibrary'

const entry = { id: 'checkpoint-a', name: 'Baseline', created_at: '2026-11-10T20:00:00Z', configuration: { runtime_id: 'traceharness', model_id: 'provider/model', task_id: 'repository/task' } }
const callbacks = () => ({ onCreate: vi.fn(), onRename: vi.fn(), onDelete: vi.fn(), onRestore: vi.fn(), onCompare: vi.fn(), onExport: vi.fn() })
afterEach(() => { cleanup(); vi.restoreAllMocks() })

describe('full configuration checkpoints view', () => {
  it('makes scope clear and creates a named checkpoint without browser storage or network writes', async () => {
    const actions = callbacks(); const fetch = vi.spyOn(globalThis, 'fetch'); const storage = vi.spyOn(Storage.prototype, 'setItem')
    render(<ConfigurationLibrary {...actions} />)
    expect(screen.getByText('This tab only')).toBeTruthy()
    expect(screen.getByText(/They do not save to your account or start a run/)).toBeTruthy()
    expect(screen.getByText('No checkpoints in this tab')).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Create checkpoint' }).disabled).toBe(true)
    fireEvent.change(screen.getByRole('textbox', { name: 'Checkpoint name' }), { target: { value: '  Alternative A  ' } })
    fireEvent.submit(screen.getByRole('textbox', { name: 'Checkpoint name' }).closest('form'))
    await waitFor(() => expect(actions.onCreate).toHaveBeenCalledWith('Alternative A'))
    await waitFor(() => expect(screen.getByRole('textbox', { name: 'Checkpoint name' }).value).toBe(''))
    expect(fetch).not.toHaveBeenCalled(); expect(storage).not.toHaveBeenCalled()
  })
  it('identifies every row action and passes stable checkpoint IDs to its owner', async () => {
    const actions = callbacks(); render(<ConfigurationLibrary entries={[entry]} {...actions} />)
    expect(screen.getByText('provider/model')).toBeTruthy(); expect(screen.getByText('repository/task')).toBeTruthy()
    for (const [action, handler] of [['Restore', 'onRestore'], ['Compare', 'onCompare'], ['Export', 'onExport'], ['Delete', 'onDelete']]) {
      const button = screen.getByRole('button', { name: `${action} checkpoint Baseline` })
      await waitFor(() => expect(button.disabled).toBe(false))
      fireEvent.click(button)
      await waitFor(() => expect(actions[handler]).toHaveBeenCalledExactlyOnceWith('checkpoint-a'))
    }
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('textbox', { name: 'Checkpoint name' })))
    expect(actions.onCreate).not.toHaveBeenCalled()
  })
  it('renames inline and returns keyboard focus after save or Escape', async () => {
    const actions = callbacks(); render(<ConfigurationLibrary entries={[entry]} {...actions} />)
    const rename = screen.getByRole('button', { name: 'Rename checkpoint Baseline' })
    fireEvent.click(rename)
    const input = screen.getByRole('textbox', { name: 'New checkpoint name' })
    expect(document.activeElement).toBe(input)
    fireEvent.change(input, { target: { value: 'Revised baseline' } }); fireEvent.submit(input.closest('form'))
    await waitFor(() => expect(actions.onRename).toHaveBeenCalledWith('checkpoint-a', 'Revised baseline'))
    await waitFor(() => expect(document.activeElement).toBe(rename))
    fireEvent.click(rename); fireEvent.keyDown(screen.getByRole('textbox', { name: 'New checkpoint name' }), { key: 'Escape' })
    expect(screen.queryByRole('textbox', { name: 'New checkpoint name' })).toBeNull()
    expect(document.activeElement).toBe(rename)
  })
  it('keeps the typed name and reports rejected operations without claiming success', async () => {
    const actions = callbacks(); actions.onCreate.mockRejectedValue(new Error('This tab has no storage space.'))
    render(<ConfigurationLibrary {...actions} />)
    fireEvent.change(screen.getByRole('textbox', { name: 'Checkpoint name' }), { target: { value: 'Keep my name' } })
    fireEvent.click(screen.getByRole('button', { name: 'Create checkpoint' }))
    expect(await screen.findByRole('alert')).toHaveProperty('textContent', 'This tab has no storage space.')
    expect(screen.getByRole('textbox', { name: 'Checkpoint name' }).value).toBe('Keep my name')
  })
  it('renders comparison direction and text-only prompt additions/removals with truncation notice', () => {
    const comparison = { id: entry.id, changes: [{ key: 'model_id', label: 'Model', before: 'provider/old', after: 'provider/new' }], prompt: { changed: true, truncated: true, lines: [{ kind: 'removed', text: '<script>old()</script>' }, { kind: 'added', text: 'New instructions' }] } }
    const { container } = render(<ConfigurationLibrary entries={[entry]} {...callbacks()} comparison={comparison} />)
    const panel = screen.getByRole('region', { name: 'Comparison with Baseline' })
    expect(within(panel).getByText('Current configuration → checkpoint')).toBeTruthy()
    expect(within(panel).getByText('provider/old')).toBeTruthy(); expect(within(panel).getByText('provider/new')).toBeTruthy()
    expect(within(panel).getByLabelText('Prompt changes').textContent).toContain('<script>old()</script>')
    expect(container.querySelector('script')).toBeNull()
    expect(within(panel).getByText(/Prompt preview is shortened/)).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Compare checkpoint Baseline' }).getAttribute('aria-expanded')).toBe('true')
  })
  it('shows identical configurations honestly and disables mutations while its owner is busy', () => {
    render(<ConfigurationLibrary entries={[entry]} {...callbacks()} busy comparison={{ id: entry.id, changes: [], prompt: { changed: false } }} />)
    expect(screen.getByRole('status').textContent).toBe('This checkpoint matches the current configuration.')
    for (const button of screen.getAllByRole('button')) expect(button.disabled).toBe(true)
    expect(screen.getByRole('textbox', { name: 'Checkpoint name' }).disabled).toBe(true)
  })
  it('accepts 80 emoji characters and explains an 81-character name without truncating it', async () => {
    const actions = callbacks(); render(<ConfigurationLibrary {...actions} />)
    const input = screen.getByRole('textbox', { name: 'Checkpoint name' })
    const oversized = '🧪'.repeat(81)
    fireEvent.change(input, { target: { value: oversized } })
    expect(input.value).toBe(oversized)
    expect(input.getAttribute('maxlength')).toBeNull()
    expect(screen.getByRole('status').textContent).toContain('81 / 80 Unicode characters')
    expect(screen.getByRole('button', { name: 'Create checkpoint' }).disabled).toBe(true)
    fireEvent.submit(input.closest('form'))
    expect(screen.getByRole('alert').textContent).toContain('1 to 80 Unicode characters')
    expect(actions.onCreate).not.toHaveBeenCalled()
    fireEvent.change(input, { target: { value: '🧪'.repeat(80) } })
    expect(screen.getByRole('button', { name: 'Create checkpoint' }).disabled).toBe(false)
    fireEvent.click(screen.getByRole('button', { name: 'Create checkpoint' }))
    await waitFor(() => expect(actions.onCreate).toHaveBeenCalledWith('🧪'.repeat(80)))
  })
  it('uses the same Unicode name limit when renaming a checkpoint', async () => {
    const actions = callbacks(); render(<ConfigurationLibrary entries={[entry]} {...actions} />)
    fireEvent.click(screen.getByRole('button', { name: 'Rename checkpoint Baseline' }))
    const input = screen.getByRole('textbox', { name: 'New checkpoint name' })
    fireEvent.change(input, { target: { value: '🧪'.repeat(81) } })
    expect(input.value).toBe('🧪'.repeat(81))
    expect(screen.getByRole('status').textContent).toContain('Shorten this name to save it.')
    expect(screen.getByRole('button', { name: 'Save name' }).disabled).toBe(true)
    expect(actions.onRename).not.toHaveBeenCalled()
    fireEvent.change(input, { target: { value: '🧪'.repeat(80) } })
    fireEvent.click(screen.getByRole('button', { name: 'Save name' }))
    await waitFor(() => expect(actions.onRename).toHaveBeenCalledWith(entry.id, '🧪'.repeat(80)))
  })
})
