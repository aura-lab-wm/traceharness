// @vitest-environment jsdom
/* The hover card in the page: one component beside one trigger, and the hint layer that
   gives every [data-hint] in the rig the same card in place of the browser's native title. */
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest'
import { render, fireEvent, cleanup, act } from '@testing-library/react'
import { HoverCard, HintLayer } from './HoverCard'
import { InfoTip } from './Inspector'
import { OPEN_DELAY, CLOSE_DELAY } from './hover-intent'

const card = (c) => c.querySelector('.rg-hc-card')
const isOpen = (el) => el.getAttribute('data-open') === 'true'
const later = (ms) => act(() => { vi.advanceTimersByTime(ms) })
const mouse = { pointerType: 'mouse' }

beforeEach(() => { vi.useFakeTimers() })
afterEach(() => { cleanup(); vi.useRealTimers() })

describe('HoverCard', () => {
  const draw = (onOpenChange) => render(<p>Before <HoverCard el="hc" onOpenChange={onOpenChange} content={<span>One sentence. <a href="#/rig/guide:glossary:flip">Learn more →</a></span>}><button type="button">flip</button></HoverCard> after.</p>)

  it('keeps its words in the document, hidden, and describes its trigger with them', () => {
    const { container } = draw()
    const c = card(container)
    expect(c.textContent).toContain('One sentence.')
    expect(isOpen(c)).toBe(false)
    expect(container.querySelector('button').getAttribute('aria-describedby')).toBe(c.id)
    expect(c.id).toMatch(/^rg-hc-/)
  })
  it('opens after the open delay and closes 100 ms after the pointer leaves', () => {
    const { container } = draw()
    const a = container.querySelector('[data-el="hc"]')
    fireEvent.pointerEnter(a, mouse)
    later(OPEN_DELAY - 1)
    expect(isOpen(card(container))).toBe(false)
    later(1)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerLeave(a, mouse)
    later(CLOSE_DELAY - 1)
    expect(isOpen(card(container))).toBe(true)
    later(1)
    expect(isOpen(card(container))).toBe(false)
  })
  it('opens at once on keyboard focus, and stays open while the focus moves into the card', () => {
    const told = vi.fn()
    const { container } = draw(told)
    const b = container.querySelector('button')
    act(() => { b.focus() })
    expect(isOpen(card(container))).toBe(true)
    expect(told.mock.calls).toEqual([[true]])
    const link = card(container).querySelector('a')
    act(() => { link.focus() })
    expect(isOpen(card(container))).toBe(true)
    expect(told.mock.calls).toEqual([[true]])     // it never closed on the way into the card
    act(() => { link.blur() })
    expect(isOpen(card(container))).toBe(false)
    expect(told.mock.calls).toEqual([[true], [false]])
  })
  it('Esc closes it and goes no further; with the card closed Esc reaches the page', () => {
    const { container } = draw()
    const page = vi.fn()
    window.addEventListener('keydown', page)
    act(() => { container.querySelector('button').focus() })
    fireEvent.keyDown(container.querySelector('button'), { key: 'Escape' })
    expect(isOpen(card(container))).toBe(false)
    expect(page).not.toHaveBeenCalled()
    fireEvent.keyDown(container.querySelector('button'), { key: 'Escape' })
    expect(page).toHaveBeenCalledTimes(1)
    window.removeEventListener('keydown', page)
  })
  it('a scroll inside a tall card leaves the card where it is', () => {
    const { container } = draw()
    act(() => { container.querySelector('button').focus() })
    const c = card(container)
    c.style.maxHeight = '50px'
    fireEvent.scroll(c)
    expect(c.style.maxHeight).toBe('50px')
    fireEvent.scroll(document)
    expect(c.style.maxHeight).toBe('')           // a page scroll places it again
  })
  it('a tap pins it until a tap elsewhere', () => {
    const { container } = draw()
    const b = container.querySelector('button')
    fireEvent.pointerDown(b, { pointerType: 'touch' })
    fireEvent.click(b)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerLeave(container.querySelector('[data-el="hc"]'), { pointerType: 'touch' })
    later(1000)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerDown(document.body, { pointerType: 'touch' })
    expect(isOpen(card(container))).toBe(false)
  })
  it('a mouse press on the trigger closes a card that the hover opened', () => {
    const { container } = draw()
    const a = container.querySelector('[data-el="hc"]')
    fireEvent.pointerEnter(a, mouse); later(OPEN_DELAY)
    fireEvent.pointerDown(container.querySelector('button'), mouse)
    fireEvent.click(container.querySelector('button'))
    expect(isOpen(card(container))).toBe(false)
  })
  it('a toggle card opens and pins on click (the pointer leaving keeps it); a second click closes it', () => {
    const { container } = render(<HoverCard el="t" toggle content="Words"><button type="button">i</button></HoverCard>)
    const b = container.querySelector('button')
    fireEvent.click(b)
    expect(isOpen(card(container))).toBe(true)
    expect(b.getAttribute('aria-expanded')).toBe('true')
    fireEvent.click(b)
    expect(isOpen(card(container))).toBe(false)
    fireEvent.click(b)
    fireEvent.pointerLeave(container.querySelector('[data-el="t"]'), mouse)
    later(CLOSE_DELAY * 10)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerDown(document.body, mouse)
    expect(isOpen(card(container))).toBe(false)
  })
  it('a toggle card the hover opened stays open when clicked: the click pins it', () => {
    const { container } = render(<HoverCard el="t" toggle content="Words"><button type="button">i</button></HoverCard>)
    const a = container.querySelector('[data-el="t"]'), b = container.querySelector('button')
    fireEvent.pointerEnter(a, mouse); later(OPEN_DELAY)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerDown(b, mouse); fireEvent.click(b)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerLeave(a, mouse); later(CLOSE_DELAY * 10)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerDown(b, mouse); fireEvent.click(b)
    expect(isOpen(card(container))).toBe(false)
  })
})

describe('InfoTip is a HoverCard', () => {
  it('the (i) is a button named by its label, its words stay in the document; hover shows it, a click pins it, Esc closes it', () => {
    const { container } = render(<InfoTip label="What cached means" el="info"><p>Cached tokens are…</p></InfoTip>)
    const b = container.querySelector('button')
    expect(b.getAttribute('aria-label')).toBe('What cached means')
    expect(container.querySelector('[data-el="info"]').textContent).toContain('Cached tokens are…')
    fireEvent.pointerEnter(container.querySelector('[data-el="info"]'), mouse); later(OPEN_DELAY)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerLeave(container.querySelector('[data-el="info"]'), mouse)
    later(CLOSE_DELAY)
    expect(isOpen(card(container))).toBe(false)
    fireEvent.click(b)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.pointerLeave(container.querySelector('[data-el="info"]'), mouse)
    later(CLOSE_DELAY * 10)
    expect(isOpen(card(container))).toBe(true)
    fireEvent.keyDown(b, { key: 'Escape' })
    expect(isOpen(card(container))).toBe(false)
  })
})

describe('HintLayer', () => {
  const draw = () => render(<div className="rig"><HintLayer />
    <span data-hint="Exactly 2,416,343,635">2.42B</span>
    <button type="button" data-hint="Copy run id" aria-label="Copy">c</button>
    <button type="button" data-hint="Second hint">d</button>
    <span>plain</span></div>)
  const hint = () => document.getElementById('rg-hint')

  it('one card for every hint; it opens after the open delay, with the hint text, and describes the target', () => {
    const { container } = draw()
    const s = container.querySelector('span[data-hint]')
    fireEvent.pointerOver(s, mouse)
    later(OPEN_DELAY - 1)
    expect(isOpen(hint())).toBe(false)
    later(1)
    expect(isOpen(hint())).toBe(true)
    expect(hint().textContent).toBe('Exactly 2,416,343,635')
    expect(hint().getAttribute('role')).toBe('tooltip')
    expect(s.getAttribute('aria-describedby')).toBe('rg-hint')
    fireEvent.pointerOut(s, { ...mouse, relatedTarget: document.body })
    later(CLOSE_DELAY)
    expect(isOpen(hint())).toBe(false)
    expect(s.hasAttribute('aria-describedby')).toBe(false)
  })
  it('opens at once on keyboard focus and keeps an aria-describedby the target already had', () => {
    const { container } = draw()
    const b = container.querySelector('button[aria-label="Copy"]')
    b.setAttribute('aria-describedby', 'why')
    act(() => { b.focus() })
    expect(isOpen(hint())).toBe(true)
    expect(b.getAttribute('aria-describedby')).toBe('why rg-hint')
    act(() => { b.blur() })
    expect(isOpen(hint())).toBe(false)
    expect(b.getAttribute('aria-describedby')).toBe('why')
  })
  it('moving from one hint to the next while it is open swaps the words at once', () => {
    const { container } = draw()
    const [s, b1, b2] = container.querySelectorAll('[data-hint]')
    fireEvent.pointerOver(s, mouse); later(OPEN_DELAY)
    fireEvent.pointerOut(s, { ...mouse, relatedTarget: b2 })
    fireEvent.pointerOver(b2, mouse)
    expect(isOpen(hint())).toBe(true)
    expect(hint().textContent).toBe('Second hint')
    expect(s.hasAttribute('aria-describedby')).toBe(false)
    expect(b2.getAttribute('aria-describedby')).toBe('rg-hint')
    expect(b1.hasAttribute('aria-describedby')).toBe(false)
  })
  it('the pointer reaching a plain element closes it, even when the target went away without a pointerout', () => {
    const { container } = draw()
    const s = container.querySelector('span[data-hint]')
    fireEvent.pointerOver(s, mouse); later(OPEN_DELAY)
    fireEvent.pointerOver(container.querySelector('span:not([data-hint])'), mouse)
    later(CLOSE_DELAY)
    expect(isOpen(hint())).toBe(false)
  })
  it('Esc closes it and still reaches the menu or page under it (a hint is no layer); a press closes it; a tap pins it', () => {
    const { container } = draw()
    const s = container.querySelector('span[data-hint]')
    const page = vi.fn()
    window.addEventListener('keydown', page)
    fireEvent.pointerOver(s, mouse); later(OPEN_DELAY)
    fireEvent.keyDown(document.body, { key: 'Escape' })
    expect(isOpen(hint())).toBe(false)
    expect(page).toHaveBeenCalledTimes(1)
    window.removeEventListener('keydown', page)
    fireEvent.pointerOver(s, mouse); later(OPEN_DELAY)
    fireEvent.pointerDown(s, mouse)
    expect(isOpen(hint())).toBe(false)
    fireEvent.pointerDown(s, { pointerType: 'touch' })
    expect(isOpen(hint())).toBe(true)
    fireEvent.pointerOut(s, { pointerType: 'touch', relatedTarget: document.body })
    later(1000)
    expect(isOpen(hint())).toBe(true)
    fireEvent.pointerDown(document.body, { pointerType: 'touch' })
    expect(isOpen(hint())).toBe(false)
  })
  it('a scroll inside the hint card leaves it where it is', () => {
    const { container } = draw()
    fireEvent.pointerOver(container.querySelector('span[data-hint]'), mouse); later(OPEN_DELAY)
    hint().style.maxHeight = '40px'
    fireEvent.scroll(hint())
    expect(hint().style.maxHeight).toBe('40px')
  })
  it('an empty hint opens nothing', () => {
    const { container } = render(<div><HintLayer /><span data-hint="">x</span></div>)
    fireEvent.pointerOver(container.querySelector('span'), mouse); later(OPEN_DELAY)
    expect(isOpen(hint())).toBe(false)
  })
})
